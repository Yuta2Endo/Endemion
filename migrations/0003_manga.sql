-- Каталог аниме заменён каталогом манги, манхвы и маньхуа.
-- Пользователи и сессии не меняются. Библиотека пересоздаётся: её записи ссылались на аниме,
-- а у тайтлов теперь главы вместо серий (на момент замены библиотека была пустой)

DROP TABLE IF EXISTS library;
DROP TABLE IF EXISTS anime;

CREATE TABLE titles (
  id INTEGER PRIMARY KEY,
  title TEXT NOT NULL,
  -- manga (Япония), manhwa (Корея), manhua (Китай)
  type TEXT NOT NULL CHECK (type IN ('manga', 'manhwa', 'manhua')),
  year INTEGER NOT NULL,
  -- ongoing — выходит, completed — выпуск завершён
  status TEXT NOT NULL CHECK (status IN ('ongoing', 'completed')),
  -- Сколько глав уже вышло
  chapters INTEGER NOT NULL,
  rating REAL NOT NULL,
  -- JSON-массив жанров
  genres TEXT NOT NULL,
  author TEXT NOT NULL,
  -- Команда перевода
  translator TEXT NOT NULL,
  symbol TEXT NOT NULL,
  -- CSS-градиент обложки
  poster TEXT NOT NULL,
  description TEXT NOT NULL,
  -- Когда вышла последняя глава: для ленты обновлений
  updated_at TEXT NOT NULL
);

CREATE TABLE library (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title_id INTEGER NOT NULL REFERENCES titles(id) ON DELETE CASCADE,
  favorite INTEGER NOT NULL DEFAULT 0,
  status TEXT CHECK (status IN ('planned', 'reading', 'completed', 'dropped')),
  -- Сколько глав прочитано
  chapter INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (user_id, title_id)
);

